# -*- coding: utf-8 -*-
"""
build_feixes.py — writes ../neuro-feixes.js, the white-matter bundles used by the 3D scenes of
«Por dentro do cérebro» (memory: hippocampus <-> cortex; hearing: the nerve from the inner ear to the brainstem).
The atlas also has an «acoustic radiation» (AR), but its streamlines end in the white matter of the parietal lobe,
not in the auditory cortex, so the scenes draw that last stretch as a simplified path instead of using it.

Source: HCP1065 tractography atlas (Fang-Cheng Yeh, 2022, Nature Communications 13, 4933), CC BY-SA 4.0:
    https://github.com/data-others/atlas/releases/download/hcp1065/hcp1065_avg_tracts_trk.zip   (about 590 MB)

What it does, for each bundle in TRACTS:
  1. reads the streamlines (millimetres, MNI152 space);
  2. moves them to the space of the brain model (FreeSurfer fsaverage = MNI305), with the inverse of
     FreeSurfer's fsaverage -> MNI152 matrix;
  3. keeps N streamlines chosen at random (fixed seed) and resamples each to K points equally spaced;
  4. turns every streamline the same way round (see ORDER), so that a signal can travel along it;
  5. stores positions as 16-bit integers (hundredths of a millimetre), base64, as cp4/cerebro3d-dados.js does.

Usage:  pip install nibabel numpy ;  python3 build_feixes.py /path/to/hcp1065_avg_tracts_trk.zip
"""
import sys, zipfile, gzip, io, base64, json, os
import numpy as np
import nibabel as nib

# fsaverage (MNI305) -> MNI152, from the FreeSurfer documentation (CoordinateSystems)
M = np.array([[0.9975, -0.0073, 0.0176, -0.0429], [0.0146, 1.0009, -0.0024, 1.5496], [-0.0130, -0.0093, 0.9971, 1.1840], [0, 0, 0, 1]])
TO_305 = np.linalg.inv(M)

# bundle: (folder, streamlines kept, points per streamline, which end comes first)
TRACTS = {
    'ILF_L':   ('association', 90, 24, 'back'),     # inferior longitudinal fasciculus: occipital (vision) -> temporal lobe
    'C_PHP_L': ('association', 70, 24, 'top'),      # cingulum, parahippocampal-parietal part: parietal -> next to the hippocampus
    'UF_L':    ('association', 70, 22, 'front'),    # uncinate fasciculus: frontal -> front of the temporal lobe
    'F_L':     ('projection', 60, 24, 'back'),      # fornix: the main exit of the hippocampus
    'IFOF_L':  ('association', 90, 26, 'back'),     # inferior fronto-occipital fasciculus: occipital <-> frontal (cortex to cortex)
    'SLF2_L':  ('association', 90, 24, 'back'),     # superior longitudinal fasciculus II: parietal <-> frontal (cortex to cortex)
    'CNVIII_L': ('cranial nerve', 40, 12, 'lateral'),   # vestibulocochlear nerve: inner ear -> brainstem (its first third is used)
    'CNVIII_R': ('cranial nerve', 40, 12, 'lateral'),
}
FIRST = {'back': lambda a, b: a[1] < b[1], 'front': lambda a, b: a[1] > b[1], 'top': lambda a, b: a[2] > b[2],
         'medial': lambda a, b: abs(a[0]) < abs(b[0]), 'lateral': lambda a, b: abs(a[0]) > abs(b[0])}

def resample(line, k):
    """k points equally spaced along a streamline."""
    d = np.r_[0, np.cumsum(np.linalg.norm(np.diff(line, axis=0), axis=1))]
    t = np.linspace(0, d[-1], k)
    return np.stack([np.interp(t, d, line[:, i]) for i in range(3)], axis=1)

def main(zip_path, out_path):
    rng = np.random.default_rng(7)
    z = zipfile.ZipFile(zip_path); out = {}
    for name, (folder, n, k, order) in TRACTS.items():
        raw = gzip.decompress(z.read(f'{folder}/{name}.trk.gz'))
        lines = nib.streamlines.load(io.BytesIO(raw)).streamlines
        long_enough = [i for i, s in enumerate(lines) if len(s) >= 4]
        pick = rng.choice(long_enough, size=min(n, len(long_enough)), replace=False)
        pts = []
        for i in sorted(pick):
            s = np.asarray(lines[i], dtype=float)
            s = (np.c_[s, np.ones(len(s))] @ TO_305.T)[:, :3]
            s = resample(s, k)
            if not FIRST[order](s[0], s[-1]): s = s[::-1]
            pts.append(s)
        arr = np.round(np.concatenate(pts) * 100).astype('<i2')
        out[name] = {'p': base64.b64encode(arr.tobytes()).decode(), 'n': len(pts), 'k': k}
        a = np.concatenate(pts); print(name, len(lines), '->', len(pts), 'x', k, '| start', np.round(np.mean([p[0] for p in pts], 0)), 'end', np.round(np.mean([p[-1] for p in pts], 0)))
    js = ('/* neuro-feixes.js — generated by tools/build_feixes.py; do not edit by hand.\n'
          '   White-matter bundles of the HCP1065 tractography atlas (Fang-Cheng Yeh, 2022), CC BY-SA 4.0, in the space of the\n'
          '   brain model (MNI305). Each bundle: n streamlines of k points; p = base64 of 16-bit integers, hundredths of a millimetre. */\n'
          'window.NEURO_FEIXES = ' + json.dumps(out, separators=(',', ':')) + ';\n')
    open(out_path, 'w').write(js); print(len(js) // 1024, 'KB')

if __name__ == '__main__':
    here = os.path.dirname(os.path.abspath(__file__))
    main(sys.argv[1], os.path.join(here, '..', 'neuro-feixes.js'))
