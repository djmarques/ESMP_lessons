"""Extract the speaker notes of a PowerPoint deck into notes.js for the lesson site.

Usage:  python tools/extract_notes.py deck.pptx notes.js

The output defines window.NOTES = {"<slide number>": ["paragraph", ...], ...}.
Slide numbers are the deck's own (1-based, hidden slides included), which is
what each web slide's data-src attribute refers to. A .js file is used instead
of .json so the site also works when index.html is opened straight from disk,
where browsers block fetch() of local files.
"""
import json
import sys

from pptx import Presentation  # pip install python-pptx

deck_path, output_path = sys.argv[1], sys.argv[2]

# Collect the notes of every slide that has any, split into paragraphs.
notes = {}
for number, slide in enumerate(Presentation(deck_path).slides, start=1):
    if not slide.has_notes_slide:
        continue
    text = slide.notes_slide.notes_text_frame.text.strip()
    if text:
        # Each non-empty line becomes one paragraph in the notes panel.
        notes[number] = [line.strip() for line in text.split("\n") if line.strip()]

# Write a script that assigns the notes to a global the site reads (app.js, renderNotes).
with open(output_path, "w", encoding="utf-8") as f:
    f.write("/* Generated by tools/extract_notes.py from the PowerPoint speaker notes. Do not edit by hand. */\n")
    f.write("window.NOTES = " + json.dumps(notes, ensure_ascii=False, indent=0) + ";\n")
print(len(notes), "slides with notes")
